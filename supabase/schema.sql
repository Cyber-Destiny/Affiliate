create extension if not exists pg_trgm with schema extensions;

-- ---------------------------------------------------------------------------
-- Tables
-- ---------------------------------------------------------------------------

create table if not exists public.categories (
  id smallint generated by default as identity primary key,
  name text not null unique,
  icon text not null default '',
  sort_order int not null default 0
);

create table if not exists public.clips (
  id uuid primary key default gen_random_uuid(),
  -- File name without extension, e.g. "leave-me-alone". Re-importing the same
  -- file name updates the clip instead of creating a duplicate.
  slug text not null unique,
  title text not null,
  category text not null references public.categories (name) on update cascade,
  tags text[] not null default '{}',
  mp4_url text not null,
  mp3_url text not null,
  thumbnail_url text,
  duration_sec real not null default 0,
  play_count bigint not null default 0,
  send_count bigint not null default 0,
  status text not null default 'live' check (status in ('live', 'removed')),
  pinned boolean not null default false,
  created_at timestamptz not null default now(),
  -- Filled in automatically from title + tags; used by search.
  search_text text not null default ''
);

create table if not exists public.reports (
  id uuid primary key default gen_random_uuid(),
  clip_id uuid not null references public.clips (id) on delete cascade,
  reason text not null check (char_length(reason) between 1 and 500),
  contact_email text check (contact_email is null or char_length(contact_email) <= 254),
  created_at timestamptz not null default now(),
  resolved boolean not null default false
);

-- People allowed into the admin panel. Add yourself after creating your login:
--   insert into public.admins (user_id)
--   select id from auth.users where email = 'you@example.com';
create table if not exists public.admins (
  user_id uuid primary key references auth.users (id) on delete cascade,
  created_at timestamptz not null default now()
);

create index if not exists clips_trending_idx on public.clips (status, pinned desc, send_count desc);
create index if not exists clips_category_idx on public.clips (category, send_count desc);
create index if not exists clips_created_idx on public.clips (created_at desc);
create index if not exists clips_search_trgm_idx on public.clips using gin (search_text extensions.gin_trgm_ops);
create index if not exists reports_open_idx on public.reports (resolved, created_at desc);

-- ---------------------------------------------------------------------------
-- Search
-- ---------------------------------------------------------------------------

-- Lowercases, drops apostrophes, turns punctuation into spaces and squashes
-- stretched letters ("gehhhh" → "geh", "chaiii" → "chai") so the many ways
-- people spell Pidgin and slang still meet in the middle.
create or replace function public.normalize_search(t text)
returns text
language sql
immutable
as $$
  select trim(regexp_replace(
           regexp_replace(
             regexp_replace(
               regexp_replace(lower(coalesce(t, '')), '[''’`]', '', 'g'),
             '[^[:alnum:]]+', ' ', 'g'),
           '([[:alpha:]])\1\1+', '\1', 'g'),
         '\s+', ' ', 'g'))
$$;

create or replace function public.clips_set_search_text()
returns trigger
language plpgsql
as $$
begin
  new.search_text := public.normalize_search(new.title || ' ' || array_to_string(new.tags, ' '));
  return new;
end;
$$;

drop trigger if exists clips_search_text on public.clips;
create trigger clips_search_text
  before insert or update of title, tags on public.clips
  for each row execute function public.clips_set_search_text();

-- Ranking: an exact tag (or title) match first, then the phrase anywhere,
-- then every word somewhere, then close spellings. Ties go to the clip that
-- has been sent the most.
create or replace function public.search_clips(q text, max_results int default 40)
returns table (
  id uuid,
  slug text,
  title text,
  category text,
  tags text[],
  mp4_url text,
  mp3_url text,
  thumbnail_url text,
  duration_sec real,
  play_count bigint,
  send_count bigint,
  pinned boolean,
  created_at timestamptz,
  search_rank int
)
language sql
stable
set search_path = public, extensions
as $$
  with query as (
    select public.normalize_search(q) as nq
  ),
  words as (
    select w from query, unnest(string_to_array(query.nq, ' ')) as w where w <> ''
  ),
  scored as (
    select c.*,
      case
        when exists (select 1 from unnest(c.tags) as t where public.normalize_search(t) = query.nq)
          or public.normalize_search(c.title) = query.nq then 0
        when c.search_text like '%' || query.nq || '%' then 1
        when not exists (select 1 from words where c.search_text not like '%' || words.w || '%') then 2
        when not exists (select 1 from words where word_similarity(words.w, c.search_text) < 0.4) then 3
      end as rank
    from public.clips c, query
    where c.status = 'live' and query.nq <> ''
  )
  select s.id, s.slug, s.title, s.category, s.tags, s.mp4_url, s.mp3_url, s.thumbnail_url,
         s.duration_sec, s.play_count, s.send_count, s.pinned, s.created_at, s.rank
  from scored s
  where s.rank is not null
  order by s.rank, s.send_count desc, s.created_at desc
  limit greatest(1, least(coalesce(max_results, 40), 100));
$$;

-- ---------------------------------------------------------------------------
-- Counters (the app can bump these but cannot edit clips)
-- ---------------------------------------------------------------------------

create or replace function public.increment_play(p_clip_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update public.clips set play_count = play_count + 1 where id = p_clip_id and status = 'live';
$$;

create or replace function public.increment_send(p_clip_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update public.clips set send_count = send_count + 1 where id = p_clip_id and status = 'live';
$$;

-- ---------------------------------------------------------------------------
-- Access rules
-- ---------------------------------------------------------------------------

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (select 1 from public.admins where user_id = auth.uid());
$$;

alter table public.categories enable row level security;
alter table public.clips enable row level security;
alter table public.reports enable row level security;
alter table public.admins enable row level security;

drop policy if exists "categories are public" on public.categories;
create policy "categories are public" on public.categories
  for select using (true);

drop policy if exists "admins manage categories" on public.categories;
create policy "admins manage categories" on public.categories
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "live clips are public" on public.clips;
create policy "live clips are public" on public.clips
  for select using (status = 'live' or public.is_admin());

drop policy if exists "admins add clips" on public.clips;
create policy "admins add clips" on public.clips
  for insert to authenticated with check (public.is_admin());

drop policy if exists "admins edit clips" on public.clips;
create policy "admins edit clips" on public.clips
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete clips" on public.clips;
create policy "admins delete clips" on public.clips
  for delete to authenticated using (public.is_admin());

drop policy if exists "anyone can report a clip" on public.reports;
create policy "anyone can report a clip" on public.reports
  for insert to anon, authenticated with check (resolved = false);

drop policy if exists "admins read reports" on public.reports;
create policy "admins read reports" on public.reports
  for select to authenticated using (public.is_admin());

drop policy if exists "admins handle reports" on public.reports;
create policy "admins handle reports" on public.reports
  for update to authenticated using (public.is_admin()) with check (public.is_admin());

drop policy if exists "admins delete reports" on public.reports;
create policy "admins delete reports" on public.reports
  for delete to authenticated using (public.is_admin());

-- No policies on admins: it is only read through is_admin().

grant usage on schema public to anon, authenticated;
grant select on public.categories, public.clips to anon, authenticated;
grant insert on public.reports to anon, authenticated;
grant insert, update, delete on public.categories, public.clips to authenticated;
grant select, update, delete on public.reports to authenticated;
grant execute on function public.search_clips(text, int) to anon, authenticated;
grant execute on function public.increment_play(uuid) to anon, authenticated;
grant execute on function public.increment_send(uuid) to anon, authenticated;
grant execute on function public.is_admin() to anon, authenticated;
grant execute on function public.normalize_search(text) to anon, authenticated;

-- ---------------------------------------------------------------------------
-- File storage: one public bucket; only admins can upload or change files
-- ---------------------------------------------------------------------------

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('clips', 'clips', true, 10485760, array['video/mp4', 'audio/mpeg', 'image/jpeg'])
on conflict (id) do update
  set public = excluded.public,
      file_size_limit = excluded.file_size_limit,
      allowed_mime_types = excluded.allowed_mime_types;

drop policy if exists "admins read clip files" on storage.objects;
create policy "admins read clip files" on storage.objects
  for select to authenticated using (bucket_id = 'clips' and public.is_admin());

drop policy if exists "admins upload clip files" on storage.objects;
create policy "admins upload clip files" on storage.objects
  for insert to authenticated with check (bucket_id = 'clips' and public.is_admin());

drop policy if exists "admins replace clip files" on storage.objects;
create policy "admins replace clip files" on storage.objects
  for update to authenticated using (bucket_id = 'clips' and public.is_admin())
  with check (bucket_id = 'clips' and public.is_admin());

drop policy if exists "admins delete clip files" on storage.objects;
create policy "admins delete clip files" on storage.objects
  for delete to authenticated using (bucket_id = 'clips' and public.is_admin());

